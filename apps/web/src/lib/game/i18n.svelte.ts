const catalogs: Record<Locale, Record<MessageKey, string>> = { 'pt-BR': pt, en };

class I18n {
	locale = $state<Locale>('pt-BR');

	t = (key: MessageKey, params?: Record<string, string | number>): string => {
		const template = catalogs[this.locale][key] ?? key;
		if (!params) return template;
		return template.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
	};
}

export const i18n = new I18n();
export const t = i18n.t;

/** Plain-language text for an engine reason code (falls back to the code itself). */
export function reasonText(code: string): string {
	const key = `reason.${code}`;
	return key in pt ? t(key as MessageKey) : code;
}
