const catalogs: Record<Locale, Record<MessageKey, string>> = { 'pt-BR': pt, en };

class I18n {
	locale = $state<Locale>('pt-BR');

	t = (key: MessageKey, params?: Record<string, string | number>): string => {
		const template = catalogs[this.locale][key] ?? key;
		if (!params) return template;
		return template.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
	};
}

export const i18n = new I18n();
export const t = i18n.t;

/** Text for an engine CSV issue code such as "missing_column:volume" (falls back to the code). */
export function csvIssueText(code: string): string {
	const i = code.indexOf(':');
	const key = `csvIssue.${i < 0 ? code : code.slice(0, i)}`;
	return key in pt ? t(key as MessageKey, { arg: i < 0 ? '' : code.slice(i + 1) }) : code;
}

/**
 * `key` with `{n}` written in the locale ("2.000 barras" in PT-BR), or its `…One` singular form when n
 * is 1 ("em 1 barra", not "em 1 barras").
 */
export function tCount(key: MessageKey, n: number, params: Record<string, string | number> = {}): string {
	const one = `${key}One`;
	return t(n === 1 && one in pt ? (one as MessageKey) : key, { ...params, n: new Intl.NumberFormat(i18n.locale).format(n) });
}

/** Guidance for a declared CSV field the engine refused (falls back to naming the field). */
export function csvMetaText(field: string): string {
	const key = `csvMeta.${field}`;
	return key in pt ? t(key as MessageKey) : t('csv.meta', { field });
}

/** Text for a pack refusal reason such as "bad_signature" or "quota:1,2 MB" (falls back to the code itself). */
export function packReasonText(code: string): string {
	const i = code.indexOf(':');
	const key = `packReason.${i < 0 ? code : code.slice(0, i)}`;
	return key in pt ? t(key as MessageKey, { arg: i < 0 ? '' : code.slice(i + 1) }) : code;
}

/** Plain-language text for an engine reason code (falls back to the code itself). */
export function reasonText(code: string): string {
	const key = `reason.${code}`;
	return key in pt ? t(key as MessageKey) : code;
}
