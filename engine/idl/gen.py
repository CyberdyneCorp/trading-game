#!/usr/bin/env python3
"""Generate the engine's C++ enums, the C ABI JSON schema and the web client's TypeScript types
from engine/idl/tradelab.idl (syntax in that file's header).

Usage:
  python3 engine/idl/gen.py           write the generated files
  python3 engine/idl/gen.py --check   exit 1 when a generated file is stale (CI)
"""
from __future__ import annotations

import json
import pathlib
import re
import sys
from dataclasses import dataclass, field

ROOT = pathlib.Path(__file__).resolve().parents[2]
IDL = ROOT / "engine" / "idl" / "tradelab.idl"
CPP_OUT = ROOT / "engine" / "include" / "tradelab" / "idl_types.hpp"
SCHEMA_OUT = ROOT / "engine" / "tests" / "idl_schema.hpp"
TS_OUT = ROOT / "apps" / "web" / "src" / "lib" / "engine" / "types.ts"
BANNER = "GENERATED by engine/idl/gen.py from engine/idl/tradelab.idl; do not edit."
PRIMITIVES = {"string": "string", "int": "number", "bool": "boolean", "Decimal": "Decimal", "null": "null"}
CPP_BASE = {"u8": "std::uint8_t", "i8": "std::int8_t"}
TS_WIDTH = 110


class IdlError(Exception):
    pass


# --- Model ------------------------------------------------------------------------------------

@dataclass
class Member:
    name: str
    value: int
    json: str
    doc: list[str]


@dataclass
class Field:
    name: str
    type: object
    optional: bool
    doc: list[str]


@dataclass
class Decl:
    kind: str  # enum | struct | union | tuple
    name: str
    doc: list[str]
    attrs: dict[str, str] = field(default_factory=dict)
    base: str | None = None
    members: list[Member] = field(default_factory=list)
    fields: list[Field] = field(default_factory=list)
    type: object = None
    elements: list[tuple[object, bool]] = field(default_factory=list)


# --- Type expressions: ("prim", n) ("ref", n) ("lit", v) ("array", t) ("or", [t]) ---------------

TOKEN = re.compile(r'\s*(\[\]|[|()]|"[^"]*"|-?\d+|[A-Za-z_]\w*)')


def tokenize(text: str) -> list[str]:
    tokens, pos = [], 0
    text = text.rstrip()
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if m is None:
            raise IdlError(f"bad type expression: {text!r}")
        tokens.append(m.group(1))
        pos = m.end()
    return tokens


class TypeParser:
    def __init__(self, text: str) -> None:
        self.tokens = tokenize(text)
        self.pos = 0

    def parse(self) -> object:
        t = self.union()
        if self.pos != len(self.tokens):
            raise IdlError(f"unexpected {self.tokens[self.pos]!r} in type")
        return t

    def peek(self) -> str | None:
        return self.tokens[self.pos] if self.pos < len(self.tokens) else None

    def take(self) -> str:
        tok = self.peek()
        if tok is None:
            raise IdlError("type expression ends early")
        self.pos += 1
        return tok

    def union(self) -> object:
        parts = [self.postfix()]
        while self.peek() == "|":
            self.take()
            parts.append(self.postfix())
        return parts[0] if len(parts) == 1 else ("or", parts)

    def postfix(self) -> object:
        t = self.primary()
        while self.peek() == "[]":
            self.take()
            t = ("array", t)
        return t

    def primary(self) -> object:
        tok = self.take()
        if tok == "(":
            t = self.union()
            if self.take() != ")":
                raise IdlError("missing ')' in type")
            return t
        if tok.startswith('"'):
            return ("lit", tok[1:-1])
        if re.fullmatch(r"-?\d+", tok):
            return ("lit", int(tok))
        return ("prim", tok) if tok in PRIMITIVES else ("ref", tok)


def parse_type(text: str) -> object:
    return TypeParser(text).parse()


# --- Declarations -----------------------------------------------------------------------------

ENUM_RE = re.compile(r"enum\s+(\w+)\s*:\s*(u8|i8)\s*(?:\[([^\]]*)\])?\s*\{$")
STRUCT_RE = re.compile(r"struct\s+(\w+)\s*(?::\s*(\w+))?\s*\{$")
UNION_RE = re.compile(r"union\s+(\w+)\s*=\s*(.+)$")
TUPLE_RE = re.compile(r"tuple\s+(\w+)\s*=\s*\[(.*)\]$")
MEMBER_RE = re.compile(r'(\w+)\s*=\s*(-?\d+)(?:\s+"([^"]+)")?$')
FIELD_RE = re.compile(r"(\w+)(\?)?\s*:\s*(.+)$")


def snake(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def parse_attrs(text: str | None) -> dict[str, str]:
    attrs: dict[str, str] = {}
    for part in filter(None, (p.strip() for p in (text or "").split(","))):
        key, _, value = part.partition("=")
        attrs[key.strip()] = value.strip()
    return attrs


def parse_member(line: str, doc: list[str]) -> Member:
    m = MEMBER_RE.fullmatch(line)
    if m is None:
        raise IdlError(f"bad enum member: {line!r}")
    return Member(m.group(1), int(m.group(2)), m.group(3) or snake(m.group(1)), doc)


def parse_field(line: str, doc: list[str]) -> Field:
    m = FIELD_RE.fullmatch(line)
    if m is None:
        raise IdlError(f"bad struct field: {line!r}")
    return Field(m.group(1), parse_type(m.group(3)), m.group(2) == "?", doc)


def parse_tuple_elements(body: str) -> list[tuple[object, bool]]:
    elements = []
    for part in (p.strip() for p in body.split(",")):
        optional = part.endswith("?")
        elements.append((parse_type(part.rstrip("?")), optional))
    return elements


def open_block(line: str, doc: list[str]) -> Decl | None:
    m = ENUM_RE.fullmatch(line)
    if m:
        attrs = parse_attrs(m.group(3))
        attrs["base"] = m.group(2)
        return Decl("enum", m.group(1), doc, attrs)
    m = STRUCT_RE.fullmatch(line)
    if m:
        return Decl("struct", m.group(1), doc, base=m.group(2))
    return None


def one_line_decl(line: str, doc: list[str]) -> Decl:
    m = TUPLE_RE.fullmatch(line)
    if m:
        return Decl("tuple", m.group(1), doc, elements=parse_tuple_elements(m.group(2)))
    m = UNION_RE.fullmatch(line)
    if m:
        return Decl("union", m.group(1), doc, type=parse_type(m.group(2)))
    raise IdlError(f"unknown declaration: {line!r}")


def add_to_block(block: Decl, line: str, doc: list[str]) -> None:
    if block.kind == "enum":
        block.members.append(parse_member(line, doc))
    else:
        block.fields.append(parse_field(line, doc))


def parse_line(line: str, doc: list[str], block: Decl | None, decls: list[Decl]) -> Decl | None:
    """Consumes one declaration line; returns the block still open after it."""
    if block is None:
        block = open_block(line, doc)
        if block is None:
            decls.append(one_line_decl(line, doc))
        return block
    if line == "}":
        decls.append(block)
        return None
    add_to_block(block, line, doc)
    return block


def parse_idl(text: str) -> list[Decl]:
    decls: list[Decl] = []
    doc: list[str] = []
    block: Decl | None = None
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if line.startswith("///"):
            doc.append(line[3:].strip())
            continue
        if not line or line.startswith("#"):
            continue
        try:
            block = parse_line(line, doc, block, decls)
        except IdlError as e:
            raise IdlError(f"tradelab.idl:{number}: {e}") from None
        doc = []
    if block is not None:
        raise IdlError(f"tradelab.idl: unterminated block {block.name}")
    return decls


# --- Checks -----------------------------------------------------------------------------------

def type_refs(t: object) -> list[str]:
    kind, arg = t
    if kind == "ref":
        return [arg]
    if kind == "array":
        return type_refs(arg)
    if kind == "or":
        return [r for part in arg for r in type_refs(part)]
    return []


def decl_types(d: Decl) -> list[object]:
    if d.kind == "struct":
        return [f.type for f in d.fields]
    if d.kind == "union":
        return [d.type]
    return [t for t, _ in d.elements]


def check_enum(d: Decl) -> None:
    for attr in ("values", "json names"):
        seen = [m.value if attr == "values" else m.json for m in d.members]
        if len(seen) != len(set(seen)):
            raise IdlError(f"enum {d.name}: duplicate {attr}")


def check_decls(decls: list[Decl]) -> None:
    names = [d.name for d in decls]
    if len(names) != len(set(names)):
        raise IdlError("duplicate declaration name")
    known = set(names)
    for d in decls:
        if d.kind == "enum":
            check_enum(d)
            continue
        missing = {r for t in decl_types(d) for r in type_refs(t)} - known
        if d.base and d.base not in known:
            missing.add(d.base)
        if missing:
            raise IdlError(f"{d.name}: unknown type(s) {sorted(missing)}")


# --- C++ enums --------------------------------------------------------------------------------

def cpp_doc(doc: list[str], indent: str) -> list[str]:
    return [f"{indent}// {line}" for line in doc]


def cpp_enum(d: Decl) -> list[str]:
    out = cpp_doc(d.doc, "")
    out.append(f"enum class {d.name} : {CPP_BASE[d.attrs['base']]} {{")
    for m in d.members:
        out += cpp_doc(m.doc, "  ")
        out.append(f"  {m.name} = {m.value},")
    out.append("};")
    out.append("")
    out.append(f"constexpr const char* json_name({d.name} v) {{")
    out.append("  switch (v) {")
    out += [f'    case {d.name}::{m.name}: return "{m.json}";' for m in d.members]
    out += ["  }", '  return "unknown";', "}", ""]
    return out


def render_cpp(decls: list[Decl]) -> str:
    out = [
        "#pragma once",
        "",
        f"// {BANNER}",
        "// Enumerations shared by state, commands, events, the debrief and the C ABI, with the JSON name",
        "// the C ABI writes for each value (json_name). Numeric values are part of the recorded-run",
        "// format: never renumber, only append.",
        "",
        "#include <cstdint>",
        "",
        "namespace tradelab {",
        "",
    ]
    for d in decls:
        if d.kind == "enum":
            out += cpp_enum(d)
    out += ["}  // namespace tradelab", ""]
    return "\n".join(out)


# --- C ABI JSON schema (for the C++ conformance test) -----------------------------------------

def schema_type(t: object) -> object:
    kind, arg = t
    if kind in ("prim", "ref"):
        return arg
    if kind == "lit":
        return {"lit": arg}
    if kind == "array":
        return {"array": schema_type(arg)}
    return {"or": [schema_type(p) for p in arg]}


def struct_fields(d: Decl, by_name: dict[str, Decl]) -> list[Field]:
    inherited = struct_fields(by_name[d.base], by_name) if d.base else []
    return inherited + d.fields


def schema_entry(d: Decl, by_name: dict[str, Decl]) -> object:
    if d.kind == "enum":
        return {"enum": [m.json for m in d.members]}
    if d.kind == "union":
        return {"type": schema_type(d.type)}
    if d.kind == "tuple":
        required = sum(1 for _, optional in d.elements if not optional)
        return {"tuple": [schema_type(t) for t, _ in d.elements], "required": required}
    fields = [{"name": f.name, "type": schema_type(f.type), "optional": f.optional} for f in struct_fields(d, by_name)]
    return {"fields": fields}


def render_schema(decls: list[Decl]) -> str:
    by_name = {d.name: d for d in decls}
    schema = {d.name: schema_entry(d, by_name) for d in decls}
    text = json.dumps(schema, separators=(",", ":"))
    chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
    body = "\n".join(f'    R"idl({c})idl"' for c in chunks)
    return "\n".join([
        "#pragma once",
        "",
        f"// {BANNER}",
        "// Every IDL type as JSON, read by tests/test_idl_conformance.cpp to check the C ABI output:",
        '// {"Name": {"enum": [json names]} | {"fields": [{name, type, optional}]} | {"type": T} |',
        '//          {"tuple": [T], "required": n}}, T = primitive or type name | {"array": T} | {"or": [T]} | {"lit": v}.',
        "",
        "namespace tradelab::test {",
        "",
        "inline constexpr const char* kIdlSchema =",
        body + ";",
        "",
        "}  // namespace tradelab::test",
        "",
    ])


# --- TypeScript -------------------------------------------------------------------------------

def ts_name(d: Decl) -> str:
    return d.attrs.get("ts", d.name)


class TsWriter:
    def __init__(self, decls: list[Decl]) -> None:
        self.names = {d.name: ts_name(d) for d in decls}

    def type(self, t: object, in_array: bool = False) -> str:
        kind, arg = t
        if kind == "prim":
            return PRIMITIVES[arg]
        if kind == "ref":
            return self.names[arg]
        if kind == "lit":
            return f"'{arg}'" if isinstance(arg, str) else str(arg)
        if kind == "array":
            return f"{self.type(arg, in_array=True)}[]"
        text = " | ".join(self.type(p) for p in arg)
        return f"({text})" if in_array else text

    def union(self, name: str, options: list[str], doc: list[str]) -> list[str]:
        one_line = f"export type {name} = {' | '.join(options)};"
        if len(one_line) <= TS_WIDTH:
            return ts_doc(doc, "") + [one_line]
        return ts_doc(doc, "") + [f"export type {name} ="] + [f"\t| {o}" for o in options[:-1]] + [f"\t| {options[-1]};"]

    def enum(self, d: Decl) -> list[str]:
        out = self.union(ts_name(d), [f"'{m.json}'" for m in d.members], d.doc)
        if "codes" in d.attrs:
            pairs = ", ".join(f"{m.json}: {m.value}" for m in d.members)
            out.append(f"export const {d.attrs['codes']}: Record<{ts_name(d)}, number> = {{ {pairs} }};")
        return out

    def struct(self, d: Decl) -> list[str]:
        extends = f" extends {self.names[d.base]}" if d.base else ""
        out = ts_doc(d.doc, "") + [f"export interface {d.name}{extends} {{"]
        for f in d.fields:
            out += ts_doc(f.doc, "\t")
            out.append(f"\t{f.name}{'?' if f.optional else ''}: {self.type(f.type)};")
        return out + ["}"]

    def decl(self, d: Decl) -> list[str]:
        if d.kind == "enum":
            return [] if "cpp_only" in d.attrs else self.enum(d)
        if d.kind == "struct":
            return self.struct(d)
        if d.kind == "tuple":
            items = ", ".join(self.type(t) + ("?" if optional else "") for t, optional in d.elements)
            return ts_doc(d.doc, "") + [f"export type {d.name} = [{items}];"]
        options = [self.type(p) for p in d.type[1]] if d.type[0] == "or" else [self.type(d.type)]
        return self.union(d.name, options, d.doc)


def ts_doc(doc: list[str], indent: str) -> list[str]:
    if not doc:
        return []
    if len(doc) == 1:
        return [f"{indent}/** {doc[0]} */"]
    return [f"{indent}/**"] + [f"{indent} * {line}" for line in doc] + [f"{indent} */"]


def render_ts(decls: list[Decl]) -> str:
    writer = TsWriter(decls)
    out = [
        f"// {BANNER}",
        "// Shapes of the JSON returned by the engine C ABI (engine/include/tradelab/c_api.h); the engine's",
        "// conformance test (engine/tests/test_idl_conformance.cpp) checks real output against the same IDL.",
        "// Monetary fields are decimal strings of fixed-point values: display them, never do state math on them.",
        "",
        "export type Decimal = string;",
    ]
    for d in decls:
        lines = writer.decl(d)
        if lines:
            out += [""] + lines
    return "\n".join(out) + "\n"


# --- Main -------------------------------------------------------------------------------------

def outputs() -> dict[pathlib.Path, str]:
    decls = parse_idl(IDL.read_text())
    check_decls(decls)
    return {CPP_OUT: render_cpp(decls), SCHEMA_OUT: render_schema(decls), TS_OUT: render_ts(decls)}


def main(argv: list[str]) -> int:
    try:
        files = outputs()
    except IdlError as e:
        print(f"idl: {e}", file=sys.stderr)
        return 2
    if "--check" in argv:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"stale generated file: {p.relative_to(ROOT)} (run python3 engine/idl/gen.py)", file=sys.stderr)
        return 1 if stale else 0
    for p, text in files.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
