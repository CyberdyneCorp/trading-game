#!/usr/bin/env python3
"""Regenerate engine/tests/data/talib_reference.inc from TA-Lib's published regression dataset.

The input is TA-Lib's 252-bar daily reference series (src/tools/ta_regtest/test_data.c,
BSD-3-Clause, Copyright (c) 1999-2026 Mario Fortier); the expected values are TA-Lib's own outputs
for the indicator parameters the game uses. The engine test (tests/test_indicator_reference.cpp)
needs neither TA-Lib nor the network: this script is only for refreshing the vendored table.

Usage (network + TA-Lib wheel):
  uv run --python 3.12 --with TA-Lib==0.8.3 --with numpy python tools/indicator_reference.py
"""
from __future__ import annotations

import pathlib
import re
import sys
import urllib.request

TA_LIB_TAG = "main"
DATA_URL = f"https://raw.githubusercontent.com/TA-Lib/ta-lib/{TA_LIB_TAG}/src/tools/ta_regtest/test_data.c"
OUT = pathlib.Path(__file__).resolve().parents[1] / "engine" / "tests" / "data" / "talib_reference.inc"
SERIES = ("open", "high", "low", "close", "volume")


def parse_series(c_source: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for name in SERIES:
        m = re.search(rf"TA_SREF_{name}_daily_ref_0_PRIV\[252\]\s*=\s*\{{([^}}]*)\}}", c_source)
        if m is None:
            sys.exit(f"series {name} not found in {DATA_URL}")
        out[name] = [v.strip() for v in m.group(1).split(",") if v.strip()]
    return out


def compute(series: dict[str, list[str]]) -> dict[str, list[float]]:
    import numpy as np
    import talib

    o, h, low, c, v = (np.array([float(x) for x in series[k]]) for k in SERIES)
    macd, signal, hist = talib.MACD(c, 12, 26, 9)
    upper, _, lower = talib.BBANDS(c, 20, 2.0, 2.0, 0)
    return {
        "sma20": talib.SMA(c, 20), "ema50": talib.EMA(c, 50), "rsi14": talib.RSI(c, 14),
        "atr14": talib.ATR(h, low, c, 14), "vwap": talib.VWAP(h, low, c, v),
        "bbUpper": upper, "bbLower": lower, "macd": macd, "macdSignal": signal, "macdHist": hist,
        "plusDi14": talib.PLUS_DI(h, low, c, 14), "minusDi14": talib.MINUS_DI(h, low, c, 14),
        "adx14": talib.ADX(h, low, c, 14),
    }


def cell(x: float) -> str:
    return "nullptr" if x != x else f'"{x:.8f}"'


def render(series: dict[str, list[str]], outputs: dict[str, list[float]], version: str) -> str:
    lines = [
        "// GENERATED by tools/indicator_reference.py; do not edit.",
        "// Input: TA-Lib regression dataset (src/tools/ta_regtest/test_data.c, 252 daily bars).",
        f"// Expected values: TA-Lib {version} outputs, rounded to 8 decimals; nullptr = TA-Lib lookback.",
        "// TA-Lib is BSD-3-Clause, Copyright (c) 1999-2026 Mario Fortier; see TA-LIB-LICENSE.txt.",
        "// Columns: open, high, low, close, volume, " + ", ".join(outputs) + ".",
    ]
    for i in range(len(series["close"])):
        ins = ", ".join(f'"{series[k][i]}"' for k in SERIES)
        outs = ", ".join(cell(outputs[k][i]) for k in outputs)
        lines.append(f"{{{ins}, {{{outs}}}}},")
    return "\n".join(lines) + "\n"


def main() -> None:
    import talib

    with urllib.request.urlopen(DATA_URL, timeout=30) as resp:  # noqa: S310 (fixed https URL)
        source = resp.read().decode()
    series = parse_series(source)
    OUT.write_text(render(series, compute(series), talib.__version__))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
